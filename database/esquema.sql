-- 2. CONFIGURAR TIEMPO REAL (REALTIME)
-- Aseguramos que la publicación exista y asociamos las tablas.
-- NOTA: Si esto falla, intenta ejecutarlo fuera de una transacción.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_publication WHERE pubname = 'supabase_realtime') THEN
        CREATE PUBLICATION supabase_realtime;
    END IF;
END $$;

-- Intentar añadir tablas a la publicación de manera segura.
-- Si ya estaban, 'SET TABLE' simplemente refresca la lista.
ALTER PUBLICATION supabase_realtime SET TABLE 
    public.pedidos, 
    public.auditoria_financiera, 
    public.menu, 
    public.solicitudes_servicio;

-- 3. TRIGGER DE ACTUALIZACIÓN AUTOMÁTICA DE TIMESTAMP
CREATE OR REPLACE FUNCTION public.actualizar_timestamp_actualizado_en()
RETURNS TRIGGER AS $$
BEGIN
    NEW.actualizado_en = TIMEZONE('utc'::text, NOW());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_actualizar_pedidos_actualizado_en ON public.pedidos;
CREATE TRIGGER trigger_actualizar_pedidos_actualizado_en
    BEFORE UPDATE ON public.pedidos
    FOR EACH ROW
    EXECUTE FUNCTION public.actualizar_timestamp_actualizado_en();

