CREATE TABLE IF NOT EXISTS public.productos_venta (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_barras text UNIQUE NOT NULL,
    nombre text NOT NULL,
    categoria text NOT NULL CHECK (categoria IN ('licores', 'alimentos', 'carnes')),
    unidad_medida text NOT NULL CHECK (unidad_medida IN ('unid', 'kg')),
    precio_base numeric(10,2) NOT NULL,
    stock numeric(10,3) NOT NULL DEFAULT 0,
    stock_minimo numeric(10,3) NOT NULL DEFAULT 5,
    created_at timestamptz DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_productos_barras ON public.productos_venta (codigo_barras);

